/**
 * 打回阈值：命中「打回重写」级别的**不同雷区**达到这个数，就拒绝润色。
 *
 * 用户原话：「如果输入文本命中超过 3 条重灾区，必须拒绝润色，
 * 直接要求打回原稿重写」。
 *
 * ## 口径必须是「不同雷区」，不是「命中处数」
 *
 * 这是本文件里最容易搞错、也最影响实际行为的一处。两种读法差别很大：
 *   - 读法 A（错）：命中 3 处就算打回。那么一段里把「残阳如血」写了三遍就触发 ——
 *     但那是**同一种病**写了三遍，不该拦；而且改掉其中两处就等于改好了。
 *   - 读法 B（对）：命中 3 条**不同的** block 级雷区才算打回。这才对应
 *     「重灾区」的说法 —— 病得五花八门，说明这稿子从根上塌了，不是局部补丁能救的。
 *
 * 举例说明差别：同一段里「残阳如血」出现 5 次 + 「阳光明媚」1 次，
 * 读法 A 会拦（6 处），读法 B 不拦（2 条雷区）—— 后者是对的，
 * 因为这是同一个写景习惯的两面，集中改一处写景就能解决。
 *
 * 结论：阈值数的是 **distinct block 级 specId 的个数**。
 */
export const BLOCK_THRESHOLD = 3

/**
 * 判断一份检测结果该不该打回。
 *
 * 单独抽出来是因为「该怎么判」必须只有一处实现 —— 工具层、界面层、
 * 验证脚本都要用同一套口径，否则三处会出现三种结论。
 *
 * @param {object} result `detect()` 的返回值。
 * @returns {{ reject: boolean, distinctBlockSpecs: number, blockHits: number, reason: string }}
 */
export function judgeReject(result) {
  const hits = Array.isArray(result?.hits) ? result.hits : []
  const blockHits = hits.filter((h) => h?.severity === 'block')
  const distinct = new Set(blockHits.map((h) => h?.specId))
  const distinctBlockSpecs = distinct.size
  const reject = distinctBlockSpecs >= BLOCK_THRESHOLD
  return {
    reject,
    distinctBlockSpecs,
    blockHits: blockHits.length,
    reason: reject
      ? `命中 ${distinctBlockSpecs} 条不同的重灾区雷区（阈值 ${BLOCK_THRESHOLD}），按铁律拒绝润色，要求打回重写`
      : `只命中 ${distinctBlockSpecs} 条重灾区雷区（阈值 ${BLOCK_THRESHOLD}），可以润色`,
  }
}
