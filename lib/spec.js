/**
 * dsh-anti-ai-fiction — 契约层：40 条 AI 味雷区的**单一事实源**。
 *
 * 这个文件是全插件的地基。它定义：
 *   1. 四维度的 40 条雷区（名字 / 事物 / 对话 / 景色）；
 *   2. 每条雷区的**可复核判据** —— 也就是说「AI 味」不能靠模型感觉，
 *      必须落成一句能被代码查出来的话；
 *   3. 每条雷区配套的 **40 组 ❌/✅ 验收用例**。
 *
 * ## 为什么必须先有契约，而不是先写正则
 *
 * 用户给的原始材料是「❌ AI味实例 / ✅ 活人写法」的对照表。这张表天然
 * 就是一份**回归测试集**：AI 味那半必须命中，活人那半必须放行。
 * 如果先写正则、后凑用例，就容易写成「正则能过用例、但对真实稿子乱报」。
 * 所以顺序必须是：先固定用例，再写检测器，然后两条腿一起跑。
 *
 * ## 判据怎么写才算「可复核」
 *
 * 一条判据必须能回答：*机器凭什么说这里有 AI 味？*
 * 三个问题：
 *   - **触发形态**：正文里出现什么字面特征（词/句式/结构）才算命中？
 *   - **证据**：命中时要能指回原文的哪一段。
 *   - **放行条件**：什么情况下同样的特征是合法的（不能一刀切）。
 *
 * 第三条最容易被忽略。中文里「林」「雪」「光」这些字在真实小说里满地都是，
 * 一刀切报「AI 味」会把正常稿子也打成筛子。**每条规则都必须写放行条件。**
 *
 * ## 与 dsh-writing-slots 的分工（别越界）
 *
 * 本机已装 `dsh-writing-slots`，它的 `deai_polish` 查的是**句法层**的 AI 腔：
 *   - 段首连续同一人称代词（pronoun-run）
 *   - 「仿佛/似乎/宛如/犹如」明喻引导词（as-if）
 *   - 「一种……的感觉」「莫名的……」（a-kind-of-feeling）
 *   - 带方式状语的对话标签，如「他低声道」（saying-tag）
 *   - 「也就是说/这说明」过度解释（over-explain）
 *   - 重复标记的排比、对仗式收尾（symmetry）
 *   - 场景结束替读者总结意义（summary-tail）
 *
 * 本插件查的是**内容层**：名字套路、物品说明书、对话潜台词、写景套话。
 * 两者词表零重叠，是互补关系。
 *
 * **所以：不要往本文件里加句法层规则。** 「仿佛」这类该去 `polish.js` 修，
 * 不是这里。看到重复规则，说明有人越界了。
 *
 * @module dsh-anti-ai-fiction/spec
 */

